/**
 * Copies the onboarder checklist's item labels from the cleaner app into admin, so Intake progress shows the real
 * question ("Are pets allowed?") instead of the item id. Run after the cleaner checklist changes:
 *   npx tsx scripts/sync-onboarder-labels.ts [path-to-property-cleaner-hub]
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

type Item = { id: string; label: string; children?: Item[]; children_if_no?: Item[] };

const repo = resolve(process.argv[2] || "../property-cleaner-hub");
const mod = (await import(pathToFileURL(resolve(repo, "src/data/onboarderChecklist.ts")).href)) as {
  CHECKLIST_SECTIONS: { id: string; items: Item[] }[];
  PROPERTY_SETUP_ITEMS: Item[];
};

const labels: Record<string, string> = {};
/** "Coat hooks present?" → "Coat hooks", so a follow-up reads "Coat hooks · Count" instead of just "Count". */
const stem = (label: string) =>
  label.replace(/\s+(present|available|provided|installed|working|included)\?$/i, "").replace(/\?$/, "").trim();
const walk = (items: Item[], parent = "") => {
  for (const it of items) {
    const label = parent ? `${parent} · ${it.label}` : it.label;
    if (it.id && it.label) labels[it.id] = label;
    const next = parent ? `${parent} · ${stem(it.label)}` : stem(it.label);
    if (it.children) walk(it.children, next);
    if (it.children_if_no) walk(it.children_if_no, next);
  }
};
for (const sec of mod.CHECKLIST_SECTIONS) walk(sec.items);
walk(mod.PROPERTY_SETUP_ITEMS);

const out = resolve("shared/pm/onboarderItemLabels.ts");
writeFileSync(
  out,
  "/** Generated by scripts/sync-onboarder-labels.ts from the cleaner app's checklist. Do not edit by hand. */\n" +
    `export const ONBOARDER_ITEM_LABELS: Record<string, string> = ${JSON.stringify(labels, null, 0)};\n`,
);
console.log(`Wrote ${Object.keys(labels).length} labels to ${out}`);
